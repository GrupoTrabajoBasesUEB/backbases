USE Proyecto_db;

-- 1. Nombre y país de origen de las marcas colombianas.
SELECT NOMBRE_MARCA, PAIS_ORIGEN
FROM MARCA
WHERE PAIS_ORIGEN = 'Colombia'
ORDER BY NOMBRE_MARCA;

-- 2. Código, nombre y precio de los productos con precio base de venta mayor a $300.000.
SELECT CODIGO, NOMBRE_PRODUCTO, PRECIO_BASE_VENTA
FROM PRODUCTO
WHERE PRECIO_BASE_VENTA > 300000
ORDER BY PRECIO_BASE_VENTA DESC;

-- 3. Productos con precio base de venta entre $20.000 y $50.000.
SELECT CODIGO, NOMBRE_PRODUCTO, PRECIO_BASE_VENTA
FROM PRODUCTO
WHERE PRECIO_BASE_VENTA >= 20000 AND PRECIO_BASE_VENTA <= 50000
ORDER BY PRECIO_BASE_VENTA;

-- 4. Código, nombre y costo de compra de los productos que le cuestan a la ferretería menos de $10.000.
SELECT CODIGO, NOMBRE_PRODUCTO, COSTO_COMPRA
FROM PRODUCTO
WHERE COSTO_COMPRA < 10000
ORDER BY COSTO_COMPRA;

-- 5. Nombre y dirección de las sucursales de Bogotá.
SELECT NOMBRE_SUCURSAL, DIRECCION
FROM SUCURSAL
WHERE CIUDAD = 'Bogotá'
ORDER BY NOMBRE_SUCURSAL;

-- 6. Evaluaciones con calificación de 2 o menos o con entrega tardía.
SELECT ID_EVALUACION, NIT, ID_PRODUCTO, ID_SUCURSAL, CALIFICACION, CUMPLIMIENTO_TIEMPO
FROM EVALUACION
WHERE CALIFICACION <= 2 OR CUMPLIMIENTO_TIEMPO = 0
ORDER BY ID_EVALUACION;

-- 7. Registros de inventario con stock bajo (5 unidades o menos).
SELECT ID_SUCURSAL, ID_PRODUCTO, CANTIDAD_DISPONIBLE
FROM INVENTARIO
WHERE CANTIDAD_DISPONIBLE <= 5
ORDER BY CANTIDAD_DISPONIBLE, ID_SUCURSAL, ID_PRODUCTO;

-- 8. Suministros que tardan más de 5 días en llegar.
SELECT NIT, ID_PRODUCTO, ID_SUCURSAL, TIEMPO_ENTREGA_DIAS
FROM SUMINISTRO
WHERE TIEMPO_ENTREGA_DIAS > 5
ORDER BY TIEMPO_ENTREGA_DIAS DESC, NIT, ID_PRODUCTO, ID_SUCURSAL;

-- 9. Ciudades donde la cadena tiene sucursales, sin repetir.
SELECT DISTINCT CIUDAD
FROM SUCURSAL
ORDER BY CIUDAD;

-- 10. Administradores con nivel de acceso 3.
SELECT ID_EMPLEADO, NIVEL_ACCESO
FROM ADMINISTRADOR
WHERE NIVEL_ACCESO = 3
ORDER BY ID_EMPLEADO;

-- 11. Cada subcategoría con el nombre de su categoría principal.
SELECT P.NOMBRE AS PRINCIPAL, S.NOMBRE AS SUBCATEGORIA
FROM CATEGORIA P
JOIN CATEGORIA S ON P.ID_CATEGORIA = S.ID_CATEGORIA_PRINCIPAL
ORDER BY P.NOMBRE, S.NOMBRE;

-- 12. Productos más caros que el producto HM-0001.
SELECT P.CODIGO, P.NOMBRE_PRODUCTO, P.PRECIO_BASE_VENTA
FROM PRODUCTO P
JOIN PRODUCTO R ON P.PRECIO_BASE_VENTA > R.PRECIO_BASE_VENTA
WHERE R.CODIGO = 'HM-0001'
ORDER BY P.PRECIO_BASE_VENTA;

-- 13. Parejas de empleados distintos que tienen el mismo cargo.
SELECT E1.NOMBRE AS EMPLEADO_1, E2.NOMBRE AS EMPLEADO_2, E1.CARGO
FROM EMPLEADO E1
JOIN EMPLEADO E2 ON E1.CARGO = E2.CARGO AND E1.ID_EMPLEADO < E2.ID_EMPLEADO
ORDER BY E1.CARGO, E1.ID_EMPLEADO, E2.ID_EMPLEADO;

-- 14. Todas las combinaciones posibles de método de pago y sucursal.
SELECT M.TIPO, S.NOMBRE_SUCURSAL
FROM METODO_PAGO M
CROSS JOIN SUCURSAL S
ORDER BY S.NOMBRE_SUCURSAL, M.TIPO;

-- 15. Código y nombre de los productos de la marca Stanley, escrito con producto cartesiano y selección.
SELECT P.CODIGO, P.NOMBRE_PRODUCTO, M.NOMBRE_MARCA
FROM PRODUCTO P, MARCA M
WHERE P.ID_MARCA = M.ID_MARCA AND M.NOMBRE_MARCA = 'Stanley'
ORDER BY P.CODIGO;

-- 16. Productos de la subcategoría Taladros con su marca.
SELECT P.CODIGO, P.NOMBRE_PRODUCTO, M.NOMBRE_MARCA
FROM CATEGORIA C
JOIN PRODUCTO P ON C.ID_CATEGORIA = P.ID_CATEGORIA
JOIN MARCA M ON P.ID_MARCA = M.ID_MARCA
WHERE C.NOMBRE = 'Taladros'
ORDER BY P.CODIGO;

-- 17. Vendedores con su sucursal y su comisión.
SELECT E.NOMBRE, E.APELLIDO, S.NOMBRE_SUCURSAL, V.COMISION_VENTA
FROM EMPLEADO E
JOIN VENDEDOR V ON E.ID_EMPLEADO = V.ID_EMPLEADO
JOIN SUCURSAL S ON V.ID_SUCURSAL = S.ID_SUCURSAL
ORDER BY S.NOMBRE_SUCURSAL, E.APELLIDO;

-- 18. Cada sucursal con el administrador que la dirige (relación Dirigir).
SELECT S.NOMBRE_SUCURSAL, E.NOMBRE, E.APELLIDO
FROM SUCURSAL S
JOIN EMPLEADO E ON S.ID_ADMINISTRADOR = E.ID_EMPLEADO
ORDER BY S.NOMBRE_SUCURSAL;

-- 19. Documento y nombre completo de los clientes naturales.
SELECT C.NUMERO_DOCUMENTO, N.NOMBRE, N.APELLIDO
FROM CLIENTE C
JOIN CLIENTE_NATURAL N ON C.ID_CLIENTE = N.ID_CLIENTE
ORDER BY N.APELLIDO, N.NOMBRE;

-- 20. Razón social y correos de los clientes jurídicos.
SELECT J.RAZON_SOCIAL, C.CORREO
FROM CLIENTE_JURIDICO J
JOIN CORREO_CLIENTE C ON J.ID_CLIENTE = C.ID_CLIENTE
ORDER BY J.RAZON_SOCIAL, C.CORREO;

-- 21. Líneas de la factura FV-000001 con su subtotal.
SELECT P.NOMBRE_PRODUCTO, D.CANTIDAD, D.PRECIO_UNITARIO, D.CANTIDAD * D.PRECIO_UNITARIO AS SUBTOTAL
FROM VENTA V
JOIN DETALLE_VENTA D ON V.ID_VENTA = D.ID_VENTA
JOIN PRODUCTO P ON D.ID_PRODUCTO = P.ID_PRODUCTO
WHERE V.NUMERO_FACTURA = 'FV-000001'
ORDER BY P.NOMBRE_PRODUCTO;

-- 22. Proveedores que surten a la Sede Centro, con el producto y el precio de suministro.
SELECT PR.NOMBRE_PROVEEDOR, P.NOMBRE_PRODUCTO, SU.PRECIO_SUMINISTRO
FROM SUCURSAL S
JOIN SUMINISTRO SU ON S.ID_SUCURSAL = SU.ID_SUCURSAL
JOIN PROVEEDOR PR ON SU.NIT = PR.NIT
JOIN PRODUCTO P ON SU.ID_PRODUCTO = P.ID_PRODUCTO
WHERE S.NOMBRE_SUCURSAL = 'Sede Centro'
ORDER BY PR.NOMBRE_PROVEEDOR, P.NOMBRE_PRODUCTO;

-- 23. Evaluaciones con calificación 5: proveedor, producto, sede y quién evaluó.
SELECT PR.NOMBRE_PROVEEDOR, P.NOMBRE_PRODUCTO, S.NOMBRE_SUCURSAL, E.NOMBRE, E.APELLIDO
FROM EVALUACION EV
JOIN PROVEEDOR PR ON EV.NIT = PR.NIT
JOIN PRODUCTO P ON EV.ID_PRODUCTO = P.ID_PRODUCTO
JOIN SUCURSAL S ON EV.ID_SUCURSAL = S.ID_SUCURSAL
JOIN EMPLEADO E ON EV.ID_EMPLEADO = E.ID_EMPLEADO
WHERE EV.CALIFICACION = 5
ORDER BY PR.NOMBRE_PROVEEDOR, P.NOMBRE_PRODUCTO, S.NOMBRE_SUCURSAL;

-- 24. Teléfonos de los proveedores que tienen alguna entrega evaluada como tardía.
SELECT DISTINCT P.NOMBRE_PROVEEDOR, T.TELEFONO
FROM EVALUACION E
JOIN PROVEEDOR P ON E.NIT = P.NIT
JOIN TELEFONO_PROVEEDOR T ON P.NIT = T.NIT
WHERE E.CUMPLIMIENTO_TIEMPO = 0
ORDER BY P.NOMBRE_PROVEEDOR, T.TELEFONO;

-- 25. Facturas pagadas en efectivo en la Sede Centro y el vendedor que las registró.
SELECT V.NUMERO_FACTURA, E.NOMBRE, E.APELLIDO
FROM METODO_PAGO M
JOIN VENTA V ON M.ID_METODO_PAGO = V.ID_METODO_PAGO
JOIN SUCURSAL S ON V.ID_SUCURSAL = S.ID_SUCURSAL
JOIN EMPLEADO E ON V.ID_EMPLEADO = E.ID_EMPLEADO
WHERE M.TIPO = 'Efectivo' AND S.NOMBRE_SUCURSAL = 'Sede Centro'
ORDER BY V.NUMERO_FACTURA;

-- 26. Todos los correos de contacto del negocio: clientes, proveedores y empleados.
SELECT CORREO
FROM CORREO_CLIENTE
UNION SELECT CORREO
FROM CORREO_PROVEEDOR
UNION SELECT CORREO
FROM EMPLEADO
ORDER BY CORREO;

-- 27. Teléfonos fijos de la operación: los de las sucursales y los de los proveedores.
SELECT TELEFONO
FROM SUCURSAL
UNION SELECT TELEFONO
FROM TELEFONO_PROVEEDOR
ORDER BY TELEFONO;

-- 28. Productos que están en el inventario de la Sede Centro o de la Sede Norte.
SELECT P.CODIGO, P.NOMBRE_PRODUCTO
FROM (SELECT I.ID_PRODUCTO
FROM SUCURSAL S
JOIN INVENTARIO I ON S.ID_SUCURSAL = I.ID_SUCURSAL
WHERE S.NOMBRE_SUCURSAL = 'Sede Centro'
UNION SELECT I.ID_PRODUCTO
FROM SUCURSAL S
JOIN INVENTARIO I ON S.ID_SUCURSAL = I.ID_SUCURSAL
WHERE S.NOMBRE_SUCURSAL = 'Sede Norte') U
JOIN PRODUCTO P ON U.ID_PRODUCTO = P.ID_PRODUCTO
ORDER BY P.CODIGO;

-- 29. Productos que están en el inventario de la Sede Centro y también en el de la Sede Laureles.
SELECT P.CODIGO, P.NOMBRE_PRODUCTO
FROM (SELECT I.ID_PRODUCTO
FROM SUCURSAL S
JOIN INVENTARIO I ON S.ID_SUCURSAL = I.ID_SUCURSAL
WHERE S.NOMBRE_SUCURSAL = 'Sede Centro'
INTERSECT SELECT I.ID_PRODUCTO
FROM SUCURSAL S
JOIN INVENTARIO I ON S.ID_SUCURSAL = I.ID_SUCURSAL
WHERE S.NOMBRE_SUCURSAL = 'Sede Laureles') I
JOIN PRODUCTO P ON I.ID_PRODUCTO = P.ID_PRODUCTO
ORDER BY P.CODIGO;

-- 30. Productos que se han vendido y que además tienen al menos un proveedor.
SELECT ID_PRODUCTO
FROM DETALLE_VENTA
INTERSECT SELECT ID_PRODUCTO
FROM SUMINISTRO
ORDER BY ID_PRODUCTO;

-- 31. Clientes que han comprado tanto en la Sede Centro como en la Sede Norte.
SELECT C.NUMERO_DOCUMENTO
FROM (SELECT V.ID_CLIENTE
FROM SUCURSAL S
JOIN VENTA V ON S.ID_SUCURSAL = V.ID_SUCURSAL
WHERE S.NOMBRE_SUCURSAL = 'Sede Centro'
INTERSECT SELECT V.ID_CLIENTE
FROM SUCURSAL S
JOIN VENTA V ON S.ID_SUCURSAL = V.ID_SUCURSAL
WHERE S.NOMBRE_SUCURSAL = 'Sede Norte') I
JOIN CLIENTE C ON I.ID_CLIENTE = C.ID_CLIENTE
ORDER BY C.NUMERO_DOCUMENTO;

-- 32. Productos que nunca se han vendido en la Sede Norte.
SELECT P.CODIGO, P.NOMBRE_PRODUCTO
FROM (SELECT ID_PRODUCTO
FROM PRODUCTO
EXCEPT SELECT D.ID_PRODUCTO
FROM VENTA V
JOIN DETALLE_VENTA D ON V.ID_VENTA = D.ID_VENTA
WHERE V.ID_SUCURSAL = 2) N
JOIN PRODUCTO P ON N.ID_PRODUCTO = P.ID_PRODUCTO
ORDER BY P.CODIGO;

-- 33. Administradores que no dirigen ninguna sucursal.
SELECT E.NOMBRE, E.APELLIDO
FROM (SELECT ID_EMPLEADO
FROM ADMINISTRADOR
EXCEPT SELECT ID_ADMINISTRADOR
FROM SUCURSAL) A
JOIN EMPLEADO E ON A.ID_EMPLEADO = E.ID_EMPLEADO
ORDER BY E.APELLIDO;

-- 34. Número de suministros que nunca han sido evaluados.
SELECT COUNT(*) AS SIN_EVALUAR
FROM (SELECT NIT, ID_PRODUCTO, ID_SUCURSAL
FROM SUMINISTRO
EXCEPT SELECT NIT, ID_PRODUCTO, ID_SUCURSAL
FROM EVALUACION) S;

-- 35. Clientes naturales que no tienen ningún correo registrado.
SELECT N.NOMBRE, N.APELLIDO
FROM (SELECT ID_CLIENTE
FROM CLIENTE_NATURAL
EXCEPT SELECT ID_CLIENTE
FROM CORREO_CLIENTE) C
JOIN CLIENTE_NATURAL N ON C.ID_CLIENTE = N.ID_CLIENTE
ORDER BY N.APELLIDO, N.NOMBRE;

-- 36. Productos que maneja la Sede Norte y no maneja la Sede Laureles.
SELECT P.CODIGO, P.NOMBRE_PRODUCTO
FROM (SELECT I.ID_PRODUCTO
FROM SUCURSAL S
JOIN INVENTARIO I ON S.ID_SUCURSAL = I.ID_SUCURSAL
WHERE S.NOMBRE_SUCURSAL = 'Sede Norte'
EXCEPT SELECT I.ID_PRODUCTO
FROM SUCURSAL S
JOIN INVENTARIO I ON S.ID_SUCURSAL = I.ID_SUCURSAL
WHERE S.NOMBRE_SUCURSAL = 'Sede Laureles') D
JOIN PRODUCTO P ON D.ID_PRODUCTO = P.ID_PRODUCTO
ORDER BY P.CODIGO;

-- 37. Proveedores que surten a todas las sucursales de Bogotá.
SELECT P.NOMBRE_PROVEEDOR
FROM PROVEEDOR P
WHERE NOT EXISTS (SELECT 1
FROM SUCURSAL S
WHERE S.CIUDAD = 'Bogotá' AND NOT EXISTS (SELECT 1
FROM SUMINISTRO SU
WHERE SU.NIT = P.NIT AND SU.ID_SUCURSAL = S.ID_SUCURSAL))
ORDER BY P.NOMBRE_PROVEEDOR;

-- 38. Productos que están en el inventario de todas las sedes.
SELECT P.CODIGO, P.NOMBRE_PRODUCTO
FROM PRODUCTO P
WHERE NOT EXISTS (SELECT 1
FROM SUCURSAL S
WHERE NOT EXISTS (SELECT 1
FROM INVENTARIO I
WHERE I.ID_PRODUCTO = P.ID_PRODUCTO AND I.ID_SUCURSAL = S.ID_SUCURSAL))
ORDER BY P.CODIGO;

-- 39. Sucursales que han cobrado con todos los métodos de pago con tarjeta (débito y crédito).
SELECT S.NOMBRE_SUCURSAL, S.CIUDAD
FROM SUCURSAL S
WHERE NOT EXISTS (SELECT 1
FROM METODO_PAGO M
WHERE M.TIPO IN ('Tarjeta débito', 'Tarjeta crédito') AND NOT EXISTS (SELECT 1
FROM VENTA V
WHERE V.ID_SUCURSAL = S.ID_SUCURSAL AND V.ID_METODO_PAGO = M.ID_METODO_PAGO))
ORDER BY S.NOMBRE_SUCURSAL;

-- 40. Número de productos de cada marca.
SELECT M.NOMBRE_MARCA, COUNT(P.ID_PRODUCTO) AS PRODUCTOS
FROM MARCA M
JOIN PRODUCTO P ON M.ID_MARCA = P.ID_MARCA
GROUP BY M.ID_MARCA, M.NOMBRE_MARCA
ORDER BY PRODUCTOS DESC, M.NOMBRE_MARCA;

-- 41. Stock total de cada producto sumando todas las sedes (lo que calcula la vista V_PRODUCTO_STOCK).
SELECT P.CODIGO, P.NOMBRE_PRODUCTO, SUM(I.CANTIDAD_DISPONIBLE) AS STOCK
FROM PRODUCTO P
JOIN INVENTARIO I ON P.ID_PRODUCTO = I.ID_PRODUCTO
GROUP BY P.ID_PRODUCTO, P.CODIGO, P.NOMBRE_PRODUCTO
ORDER BY STOCK DESC, P.CODIGO;

-- 42. Número de ventas y total vendido por sucursal.
SELECT S.NOMBRE_SUCURSAL, COUNT(DISTINCT V.ID_VENTA) AS VENTAS, SUM(D.CANTIDAD * D.PRECIO_UNITARIO) AS VENDIDO
FROM SUCURSAL S
JOIN VENTA V ON S.ID_SUCURSAL = V.ID_SUCURSAL
JOIN DETALLE_VENTA D ON V.ID_VENTA = D.ID_VENTA
GROUP BY S.ID_SUCURSAL, S.NOMBRE_SUCURSAL
ORDER BY VENDIDO DESC;

-- 43. Unidades vendidas por categoría principal.
SELECT C.NOMBRE AS CATEGORIA_PRINCIPAL, SUM(D.CANTIDAD) AS UNIDADES
FROM DETALLE_VENTA D
JOIN PRODUCTO PR ON D.ID_PRODUCTO = PR.ID_PRODUCTO
JOIN (SELECT S.ID_CATEGORIA_PRINCIPAL AS ID_PRINCIPAL, S.ID_CATEGORIA
FROM CATEGORIA S
JOIN CATEGORIA P ON S.ID_CATEGORIA_PRINCIPAL = P.ID_CATEGORIA
UNION SELECT R.ID_CATEGORIA AS ID_PRINCIPAL, R.ID_CATEGORIA
FROM (SELECT ID_CATEGORIA
FROM CATEGORIA
EXCEPT SELECT S.ID_CATEGORIA
FROM CATEGORIA S
JOIN CATEGORIA P ON S.ID_CATEGORIA_PRINCIPAL = P.ID_CATEGORIA) R) M ON PR.ID_CATEGORIA = M.ID_CATEGORIA
JOIN CATEGORIA C ON M.ID_PRINCIPAL = C.ID_CATEGORIA
GROUP BY C.ID_CATEGORIA, C.NOMBRE
ORDER BY UNIDADES DESC;

-- 44. Calificación promedio y número de evaluaciones de cada proveedor.
SELECT P.NOMBRE_PROVEEDOR, ROUND(AVG(E.CALIFICACION), 2) AS PROMEDIO, COUNT(E.ID_EVALUACION) AS EVALUACIONES
FROM PROVEEDOR P
JOIN EVALUACION E ON P.NIT = E.NIT
GROUP BY P.NIT, P.NOMBRE_PROVEEDOR
ORDER BY PROMEDIO DESC, P.NOMBRE_PROVEEDOR;

-- 45. Número de ventas y total cobrado con cada método de pago.
SELECT M.TIPO, COUNT(T.ID_VENTA) AS VENTAS, SUM(T.MONTO_TOTAL) AS COBRADO
FROM METODO_PAGO M
JOIN VENTA V ON M.ID_METODO_PAGO = V.ID_METODO_PAGO
JOIN V_VENTA_TOTAL T ON V.ID_VENTA = T.ID_VENTA
GROUP BY M.ID_METODO_PAGO, M.TIPO
ORDER BY COBRADO DESC;

-- 46. Comisión de cada vendedor sobre todo lo que ha vendido.
SELECT E.NOMBRE, E.APELLIDO, SUM(D.CANTIDAD * D.PRECIO_UNITARIO) AS VENDIDO, ROUND(SUM(D.CANTIDAD * D.PRECIO_UNITARIO) * V.COMISION_VENTA, 2) AS COMISION
FROM VENDEDOR V
JOIN EMPLEADO E ON V.ID_EMPLEADO = E.ID_EMPLEADO
JOIN VENTA VE ON VE.ID_EMPLEADO = V.ID_EMPLEADO
JOIN DETALLE_VENTA D ON VE.ID_VENTA = D.ID_VENTA
GROUP BY V.ID_EMPLEADO, E.NOMBRE, E.APELLIDO, V.COMISION_VENTA
ORDER BY COMISION DESC;

-- 47. Ticket promedio (valor promedio de una venta) por sucursal.
SELECT S.NOMBRE_SUCURSAL, ROUND(AVG(T.MONTO_TOTAL), 2) AS TICKET
FROM SUCURSAL S
JOIN VENTA V ON S.ID_SUCURSAL = V.ID_SUCURSAL
JOIN V_VENTA_TOTAL T ON V.ID_VENTA = T.ID_VENTA
GROUP BY S.ID_SUCURSAL, S.NOMBRE_SUCURSAL
ORDER BY TICKET DESC;

-- 48. Precio de suministro más bajo, más alto y promedio de cada producto.
SELECT P.CODIGO, MIN(S.PRECIO_SUMINISTRO) AS MINIMO, MAX(S.PRECIO_SUMINISTRO) AS MAXIMO, ROUND(AVG(S.PRECIO_SUMINISTRO), 2) AS PROMEDIO
FROM SUMINISTRO S
JOIN PRODUCTO P ON S.ID_PRODUCTO = P.ID_PRODUCTO
GROUP BY P.ID_PRODUCTO, P.CODIGO
ORDER BY P.CODIGO;

-- 49. Número de evaluaciones que hizo cada administrador.
SELECT E.NOMBRE, E.APELLIDO, COUNT(EV.ID_EVALUACION) AS EVALUACIONES
FROM EVALUACION EV
JOIN EMPLEADO E ON EV.ID_EMPLEADO = E.ID_EMPLEADO
GROUP BY E.ID_EMPLEADO, E.NOMBRE, E.APELLIDO
ORDER BY EVALUACIONES DESC, E.APELLIDO;

-- 50. Proveedores cuya calificación promedio es menor a 3,7.
SELECT P.NOMBRE_PROVEEDOR, ROUND(AVG(E.CALIFICACION), 2) AS PROMEDIO
FROM PROVEEDOR P
JOIN EVALUACION E ON P.NIT = E.NIT
GROUP BY P.NIT, P.NOMBRE_PROVEEDOR
HAVING AVG(E.CALIFICACION) < 3.7
ORDER BY PROMEDIO, P.NOMBRE_PROVEEDOR;

-- 51. Clientes con más de 5 compras.
SELECT C.NUMERO_DOCUMENTO, COUNT(V.ID_VENTA) AS COMPRAS
FROM CLIENTE C
JOIN VENTA V ON C.ID_CLIENTE = V.ID_CLIENTE
GROUP BY C.ID_CLIENTE, C.NUMERO_DOCUMENTO
HAVING COUNT(V.ID_VENTA) > 5
ORDER BY COMPRAS DESC, C.NUMERO_DOCUMENTO;

-- 52. Productos con menos de 50 unidades en toda la cadena.
SELECT P.CODIGO, P.NOMBRE_PRODUCTO, SUM(I.CANTIDAD_DISPONIBLE) AS STOCK
FROM PRODUCTO P
JOIN INVENTARIO I ON P.ID_PRODUCTO = I.ID_PRODUCTO
GROUP BY P.ID_PRODUCTO, P.CODIGO, P.NOMBRE_PRODUCTO
HAVING SUM(I.CANTIDAD_DISPONIBLE) < 50
ORDER BY STOCK, P.CODIGO;

-- 53. Sucursales con más de 3 productos en stock bajo.
SELECT S.NOMBRE_SUCURSAL, COUNT(I.ID_PRODUCTO) AS BAJOS
FROM SUCURSAL S
JOIN INVENTARIO I ON S.ID_SUCURSAL = I.ID_SUCURSAL
WHERE I.CANTIDAD_DISPONIBLE <= 5
GROUP BY S.ID_SUCURSAL, S.NOMBRE_SUCURSAL
HAVING COUNT(I.ID_PRODUCTO) > 3
ORDER BY BAJOS DESC, S.NOMBRE_SUCURSAL;

-- 54. Todos los vendedores con su número de ventas, incluidos los que no han vendido.
SELECT E.NOMBRE, E.APELLIDO, COUNT(V.ID_VENTA) AS VENTAS
FROM VENDEDOR VE
JOIN EMPLEADO E ON VE.ID_EMPLEADO = E.ID_EMPLEADO
LEFT JOIN VENTA V ON V.ID_EMPLEADO = VE.ID_EMPLEADO
GROUP BY VE.ID_EMPLEADO, E.NOMBRE, E.APELLIDO
ORDER BY VENTAS DESC, E.APELLIDO;

-- 55. Todos los productos con sus unidades vendidas, incluidos los que no se han vendido.
SELECT P.CODIGO, COALESCE(SUM(D.CANTIDAD), 0) AS UNIDADES
FROM PRODUCTO P
LEFT JOIN DETALLE_VENTA D ON P.ID_PRODUCTO = D.ID_PRODUCTO
GROUP BY P.ID_PRODUCTO, P.CODIGO
ORDER BY UNIDADES DESC, P.CODIGO;

-- 56. El producto más vendido en unidades.
SELECT P.CODIGO, P.NOMBRE_PRODUCTO, U.UNIDADES
FROM (SELECT ID_PRODUCTO, SUM(CANTIDAD) AS UNIDADES
FROM DETALLE_VENTA
GROUP BY ID_PRODUCTO) U
JOIN PRODUCTO P ON U.ID_PRODUCTO = P.ID_PRODUCTO
WHERE U.UNIDADES = (SELECT MAX(T.UNIDADES)
FROM (SELECT SUM(CANTIDAD) AS UNIDADES
FROM DETALLE_VENTA
GROUP BY ID_PRODUCTO) T);

-- 57. Capital en inventario de cada sucursal (cantidad disponible por costo de compra).
SELECT S.NOMBRE_SUCURSAL, SUM(I.CANTIDAD_DISPONIBLE * P.COSTO_COMPRA) AS CAPITAL
FROM SUCURSAL S
JOIN INVENTARIO I ON S.ID_SUCURSAL = I.ID_SUCURSAL
JOIN PRODUCTO P ON I.ID_PRODUCTO = P.ID_PRODUCTO
GROUP BY S.ID_SUCURSAL, S.NOMBRE_SUCURSAL
ORDER BY CAPITAL DESC;

-- 58. Suministros que han sido evaluados más de una vez, con su número de evaluaciones.
SELECT PR.NOMBRE_PROVEEDOR, P.CODIGO, C.ID_SUCURSAL, C.EVALUACIONES
FROM (SELECT NIT, ID_PRODUCTO, ID_SUCURSAL, COUNT(ID_EVALUACION) AS EVALUACIONES
FROM EVALUACION
GROUP BY NIT, ID_PRODUCTO, ID_SUCURSAL
HAVING COUNT(ID_EVALUACION) > 1) C
JOIN PROVEEDOR PR ON C.NIT = PR.NIT
JOIN PRODUCTO P ON C.ID_PRODUCTO = P.ID_PRODUCTO
ORDER BY C.EVALUACIONES DESC, PR.NOMBRE_PROVEEDOR, P.CODIGO;

-- 59. Productos cuyo precio base de venta supera en más de 70 % su precio de suministro más bajo.
SELECT P.CODIGO, P.PRECIO_BASE_VENTA, M.MINIMO
FROM (SELECT ID_PRODUCTO, MIN(PRECIO_SUMINISTRO) AS MINIMO
FROM SUMINISTRO
GROUP BY ID_PRODUCTO) M
JOIN PRODUCTO P ON M.ID_PRODUCTO = P.ID_PRODUCTO
WHERE P.PRECIO_BASE_VENTA > 1.7 * M.MINIMO
ORDER BY P.CODIGO;

-- 60. Clientes jurídicos que han comprado en más de una sucursal.
SELECT J.RAZON_SOCIAL, COUNT(DISTINCT V.ID_SUCURSAL) AS SEDES
FROM CLIENTE_JURIDICO J
JOIN VENTA V ON J.ID_CLIENTE = V.ID_CLIENTE
GROUP BY J.ID_CLIENTE, J.RAZON_SOCIAL
HAVING COUNT(DISTINCT V.ID_SUCURSAL) > 1
ORDER BY J.RAZON_SOCIAL;
