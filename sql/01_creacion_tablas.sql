CREATE TABLE DETALLE_VENTA (
  ID_VENTA         INT NOT NULL,
  ID_PRODUCTO      INT NOT NULL,
  CANTIDAD         INT NOT NULL,
  PRECIO_UNITARIO  DECIMAL(12,2) NOT NULL,
  CONSTRAINT PK_DETALLE_VENTA PRIMARY KEY (ID_VENTA, ID_PRODUCTO),
  CONSTRAINT CK_DETALLE_VENTA_1 CHECK (CANTIDAD > 0),
  CONSTRAINT CK_DETALLE_VENTA_2 CHECK (PRECIO_UNITARIO >= 0),
  CONSTRAINT FK_DETALLE_VENTA_VENTA FOREIGN KEY (ID_VENTA)
    REFERENCES VENTA (ID_VENTA) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT FK_DETALLE_VENTA_PRODUCTO FOREIGN KEY (ID_PRODUCTO)
    REFERENCES PRODUCTO (ID_PRODUCTO) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB;

CREATE VIEW V_PRODUCTO_STOCK AS
SELECT p.ID_PRODUCTO, p.CODIGO, p.NOMBRE_PRODUCTO,
       COALESCE(SUM(i.CANTIDAD_DISPONIBLE), 0) AS STOCK
FROM PRODUCTO p
LEFT JOIN INVENTARIO i ON i.ID_PRODUCTO = p.ID_PRODUCTO
GROUP BY p.ID_PRODUCTO, p.CODIGO, p.NOMBRE_PRODUCTO;

CREATE VIEW V_VENTA_TOTAL AS
SELECT v.ID_VENTA, v.NUMERO_FACTURA,
       COALESCE(SUM(d.CANTIDAD * d.PRECIO_UNITARIO), 0) AS MONTO_TOTAL
FROM VENTA v
LEFT JOIN DETALLE_VENTA d ON d.ID_VENTA = v.ID_VENTA
GROUP BY v.ID_VENTA, v.NUMERO_FACTURA;
