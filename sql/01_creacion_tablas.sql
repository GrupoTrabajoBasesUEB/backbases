CREATE TABLE MARCA (
  ID_MARCA      INT NOT NULL AUTO_INCREMENT,
  NOMBRE_MARCA  VARCHAR(60) NOT NULL,
  PAIS_ORIGEN   VARCHAR(60) NOT NULL,
  CONSTRAINT PK_MARCA PRIMARY KEY (ID_MARCA),
  CONSTRAINT UQ_MARCA_NOMBRE_MARCA UNIQUE (NOMBRE_MARCA)
) ENGINE=InnoDB;

CREATE TABLE CATEGORIA (
  ID_CATEGORIA            INT NOT NULL AUTO_INCREMENT,
  NOMBRE                  VARCHAR(60) NOT NULL,
  DESCRIPCION             VARCHAR(255) NULL,
  ID_CATEGORIA_PRINCIPAL  INT NULL,
  CONSTRAINT PK_CATEGORIA PRIMARY KEY (ID_CATEGORIA),
  CONSTRAINT FK_CATEGORIA_CATEGORIA FOREIGN KEY (ID_CATEGORIA_PRINCIPAL)
    REFERENCES CATEGORIA (ID_CATEGORIA) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB;

CREATE TABLE PRODUCTO (
  ID_PRODUCTO        INT NOT NULL AUTO_INCREMENT,
  CODIGO             VARCHAR(20) NOT NULL,
  NOMBRE_PRODUCTO    VARCHAR(100) NOT NULL,
  DESCRIPCION        VARCHAR(255) NULL,
  COSTO_COMPRA       DECIMAL(12,2) NOT NULL,
  PRECIO_BASE_VENTA  DECIMAL(12,2) NOT NULL,
  ID_CATEGORIA       INT NOT NULL,
  ID_MARCA           INT NOT NULL,
  CONSTRAINT PK_PRODUCTO PRIMARY KEY (ID_PRODUCTO),
  CONSTRAINT UQ_PRODUCTO_CODIGO UNIQUE (CODIGO),
  CONSTRAINT CK_PRODUCTO_1 CHECK (COSTO_COMPRA >= 0),
  CONSTRAINT CK_PRODUCTO_2 CHECK (PRECIO_BASE_VENTA >= 0),
  CONSTRAINT CK_PRODUCTO_3 CHECK (PRECIO_BASE_VENTA >= COSTO_COMPRA),
  CONSTRAINT FK_PRODUCTO_CATEGORIA FOREIGN KEY (ID_CATEGORIA)
    REFERENCES CATEGORIA (ID_CATEGORIA) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT FK_PRODUCTO_MARCA FOREIGN KEY (ID_MARCA)
    REFERENCES MARCA (ID_MARCA) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB;

